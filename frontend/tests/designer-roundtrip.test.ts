// Designer round trip, browser half (P1.16). Fields are placed and dragged the way the designer UI
// does it; the saved payload and where each field showed on screen go to
// tests/fixtures/designer_roundtrip.json. test_designer_roundtrip.py saves the payload through the
// template service, draws it with the server overlay, renders it with pdfium and checks each field
// lands on the same pixels. Regenerate with UPDATE_FIXTURES=1 yarn test after an intended change.
import { existsSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { createPinia, setActivePinia } from 'pinia'
import { beforeEach, describe, expect, it } from 'vitest'
import { displaySize, normalizedToPixels, type PageMetric } from '@/shared/coords'
import { useDesigner } from '@/staff/designer/store'
import { FIXTURES_DIR, readFixtureJson } from './fixtures'

const OUTPUT = resolve(FIXTURES_DIR, 'designer_roundtrip.json')

interface Case {
  file: string
  viewport: { width: number; height: number }
  payload: ReturnType<ReturnType<typeof useDesigner>['payload']>
  screen: Record<string, [number, number, number, number]>
}

const coords = readFixtureJson<{
  fixtures: Record<string, { pages: Array<{ page: number; cropbox: number[]; rotation: number }> }>
}>('coords.json').fixtures

function metricOf(file: string): PageMetric {
  const page = coords[file].pages[0]
  const [x0, y0, x1, y1] = page.cropbox
  return { page: 1, width: x1 - x0, height: y1 - y0, rotation: page.rotation, left: x0, bottom: y0 }
}

function design(file: string, viewportWidth: number): Case {
  const store = useDesigner()
  const metric = metricOf(file)
  const size = displaySize(metric)
  const viewport = { width: viewportWidth, height: (viewportWidth * size.height) / size.width }
  store.load({ title: `Round trip ${file}`, page_metrics: [metric], roles: [] })
  store.addRole('Signer')
  store.updateRole('Signer 1', { role_label: 'Customer' })
  store.addRole('Signer')
  store.updateRole('Signer 2', { role_label: 'Company' })

  store.activeRole = 'Customer'
  const signature = store.placeField('Signature', 1, 40, 60, viewport)
  // Drag it down and right, then widen it from the bottom-right handle.
  store.dragField(signature.field_key, { ...signature }, 'move', 23, 41, viewport)
  store.dragField(signature.field_key, { ...signature }, 'se', 37, 12, viewport)
  const name = store.placeField('Full Name', 1, viewport.width * 0.5, viewport.height * 0.6, viewport)
  store.dragField(name.field_key, { ...name }, 'w', -30, 0, viewport)
  store.activeRole = 'Company'
  const stamp = store.placeField('Company Stamp', 1, viewport.width * 0.7, viewport.height * 0.8, viewport)
  // Flung off the page: it must stop at the edge.
  store.dragField(stamp.field_key, { ...stamp }, 'move', 999, 999, viewport)
  store.selected = [name.field_key]
  store.nudgeSelected('ArrowUp', true)

  const screen: Case['screen'] = {}
  for (const field of store.fields) {
    const px = normalizedToPixels(field, viewport.width, viewport.height)
    screen[field.field_key] = [px.x, px.y, px.w, px.h].map(
      (v) => Math.round(v * 1000) / 1000,
    ) as Case['screen'][string]
  }
  return { file, viewport, payload: store.payload(), screen }
}

describe('designer round trip', () => {
  beforeEach(() => setActivePinia(createPinia()))

  it('matches the committed round trip fixture', () => {
    const cases = (
      [
        ['a4_simple.pdf', 400],
        ['rotated_270_cropbox.pdf', 390],
        ['offset_cropbox.pdf', 360],
      ] as const
    ).map(([file, width]) => {
      setActivePinia(createPinia())
      return design(file, width)
    })
    const json =
      JSON.stringify(
        { description: 'Generated by frontend/tests/designer-roundtrip.test.ts', cases },
        null,
        2,
      ) + '\n'
    if (process.env.UPDATE_FIXTURES || !existsSync(OUTPUT)) writeFileSync(OUTPUT, json)
    expect(JSON.parse(json)).toEqual(readFixtureJson('designer_roundtrip.json'))
  })

  it('keeps every field on its page', () => {
    for (const result of [design('rotated_270_cropbox.pdf', 390)]) {
      for (const field of result.payload.fields) {
        expect(field.x).toBeGreaterThanOrEqual(0)
        expect(field.y).toBeGreaterThanOrEqual(0)
        expect(field.x + field.w).toBeLessThanOrEqual(1 + 1e-9)
        expect(field.y + field.h).toBeLessThanOrEqual(1 + 1e-9)
      }
    }
  })
})

describe('designer store', () => {
  beforeEach(() => setActivePinia(createPinia()))

  it('undoes and redoes placement and deletion', () => {
    const store = useDesigner()
    store.load({ page_metrics: [metricOf('a4_simple.pdf')] })
    store.addRole('Signer')
    const field = store.placeField('Text', 1, 10, 10, { width: 400, height: 566 })
    expect(store.fields).toHaveLength(1)
    store.removeSelected()
    expect(store.fields).toHaveLength(0)
    store.undo()
    expect(store.fields.map((f) => f.field_key)).toEqual([field.field_key])
    store.undo()
    expect(store.fields).toHaveLength(0)
    store.redo()
    expect(store.fields).toHaveLength(1)
  })

  it('renaming a role moves its fields with it; removing it removes them', () => {
    const store = useDesigner()
    store.load({ page_metrics: [metricOf('a4_simple.pdf')] })
    store.addRole('Signer')
    store.placeField('Initials', 1, 10, 10, { width: 400, height: 566 })
    store.updateRole('Signer 1', { role_label: 'Tenant' })
    expect(store.fields[0].role_label).toBe('Tenant')
    store.removeRole('Tenant')
    expect(store.fields).toHaveLength(0)
  })

  it('duplicates a field to every page with unique keys', () => {
    const store = useDesigner()
    const page = metricOf('a4_simple.pdf')
    store.load({ page_metrics: [page, { ...page, page: 2 }, { ...page, page: 3 }] })
    store.addRole('Signer')
    const field = store.placeField('Initials', 1, 10, 10, { width: 400, height: 566 })
    store.duplicateToAllPages(field.field_key)
    expect(store.fields.map((f) => f.page)).toEqual([1, 2, 3])
    expect(new Set(store.fields.map((f) => f.field_key)).size).toBe(3)
  })
})
