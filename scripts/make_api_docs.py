"""Write docs/API.md from the whitelisted functions in frappe_sign/api/ (P3.9).

    python3 apps/frappe_sign/scripts/make_api_docs.py          # rewrite docs/API.md
    python3 apps/frappe_sign/scripts/make_api_docs.py --check  # exit 1 when it is out of date

No Frappe needed: it reads the source with `ast`. tests/unit/test_api_docs.py runs the check.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API = ROOT / "frappe_sign" / "api"
OUT = ROOT / "docs" / "API.md"
MODULES = {
	"staff": (
		"Staff API",
		"Logged-in users with a Sign role. Permissions are checked by the service behind each call.",
	),
	"guest": (
		"Guest API",
		"Signers, no account. Every call is POST, rate limited, and carries the link token (`open`, OTP calls) "
		"or the `X-Sign-Session` header. Failures return a stable `code`.",
	),
	"public": ("Public API", "Anyone. Rate limited. Returns no document content."),
	"portal": ("Portal API", "Logged-in users; a user gets only the documents they signed."),
}


def decorator_info(node: ast.FunctionDef) -> dict | None:
	info = {"allow_guest": False, "methods": None, "rate": None}
	whitelisted = False
	for decorator in node.decorator_list:
		call = decorator if isinstance(decorator, ast.Call) else None
		name = ast.unparse(call.func if call else decorator)
		if name.endswith("whitelist"):
			whitelisted = True
			for keyword in call.keywords if call else []:
				if keyword.arg == "allow_guest":
					info["allow_guest"] = ast.literal_eval(keyword.value)
				if keyword.arg == "methods":
					info["methods"] = ast.literal_eval(keyword.value)
		elif name.endswith("rate_limit") and call:
			values = {k.arg: ast.unparse(k.value) for k in call.keywords}
			info["rate"] = f"{values.get('limit', '?')} per {values.get('seconds', '?')} s"
	return info if whitelisted else None


def signature(node: ast.FunctionDef) -> str:
	args = ast.unparse(node.args)
	returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
	return f"{node.name}({args}){returns}"


def describe(module: str) -> list[str]:
	tree = ast.parse((API / f"{module}.py").read_text(encoding="utf-8"))
	lines = []
	for node in tree.body:
		if not isinstance(node, ast.FunctionDef):
			continue
		info = decorator_info(node)
		if info is None:
			continue
		doc = (ast.get_docstring(node) or "").strip().splitlines()
		summary = doc[0] if doc else ""
		methods = "/".join(info["methods"]) if info["methods"] else "GET or POST"
		access = "guest" if info["allow_guest"] else "login"
		extra = f", rate limit {info['rate']}" if info["rate"] else ""
		lines += [f"### `{node.name}`", "", f"`{signature(node)}`", "", f"{methods}, {access}{extra}.", ""]
		if summary:
			lines += [summary, ""]
	return lines


def error_codes() -> list[str]:
	"""A table of the stable error codes: class, code, HTTP status."""
	tree = ast.parse((ROOT / "frappe_sign" / "exceptions.py").read_text(encoding="utf-8"))
	rows = []
	for node in tree.body:
		if not isinstance(node, ast.ClassDef):
			continue
		values = {
			target.id: ast.literal_eval(item.value)
			for item in node.body
			if isinstance(item, ast.Assign)
			for target in item.targets
			if isinstance(target, ast.Name) and target.id in ("code", "http_status_code")
		}
		if "code" in values:
			rows.append(f"| `{values['code']}` | {values.get('http_status_code', 417)} | {node.name} |")
	return ["## Error codes", "", "| `code` | HTTP status | Error |", "| --- | --- | --- |", *rows, ""]


def render() -> str:
	lines = [
		"# Frappe Sign: API reference",
		"",
		"Generated by `scripts/make_api_docs.py` from the whitelisted functions in `frappe_sign/api/`. Do not edit by hand.",
		"",
		"Call a function at `/api/method/frappe_sign.api.<module>.<function>`. Staff calls need a logged-in session (cookie and CSRF token, or an API key). The `code` of a failed call is stable: switch on it, never on the message. Codes are in `frappe_sign/exceptions.py`.",
		"",
	]
	for module, (title, intro) in MODULES.items():
		lines += [f"## {title}", "", intro, "", *describe(module)]
	lines += error_codes()
	return "\n".join(lines).rstrip() + "\n"


def main() -> int:
	text = render()
	if "--check" in sys.argv:
		return 0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1
	OUT.write_text(text, encoding="utf-8")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
